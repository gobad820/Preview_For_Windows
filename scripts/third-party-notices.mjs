// Writes THIRD_PARTY_NOTICES.md: every npm package and Rust crate that ships in Preview.exe, with
// its license and the license texts it carries (packages with identical texts share one copy),
// plus the bundled font and the splash photo.
// Usage: node scripts/third-party-notices.mjs   (needs npm, cargo)
import { execFileSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const LICENSE_FILE = /^(licen[cs]e|copying|notice|unlicense)([-._].*)?$/i;

/** License texts found in a package directory, as [file name, text]. */
function licenseTexts(dir, extra = []) {
  const names = existsSync(dir) ? readdirSync(dir).filter((f) => LICENSE_FILE.test(f)) : [];
  return [...new Set([...names, ...extra])]
    .filter((f) => existsSync(join(dir, f)))
    .sort()
    .map((f) => [f, readFileSync(join(dir, f), 'utf8').replace(/\r\n/g, '\n').trim()]);
}

// ---- npm packages in the bundle (production dependencies) ----
// pdf.js reaches @napi-rs/canvas only through a Node-only require; it is not in the app bundle.
const NOT_BUNDLED = /^@napi-rs\//;
const tree = JSON.parse(execFileSync('npm', ['ls', '--omit=dev', '--all', '--json'], { cwd: root, encoding: 'utf8' }));
const npm = new Map();
(function walk(deps) {
  for (const [name, info] of Object.entries(deps ?? {})) {
    const key = `${name}@${info.version}`;
    if (npm.has(key) || !info.version || NOT_BUNDLED.test(name)) continue;
    const dir = join(root, 'node_modules', name);
    const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
    npm.set(key, { name, version: info.version, license: pkg.license ?? 'see texts', texts: licenseTexts(dir), source: `https://www.npmjs.com/package/${name}` });
    walk(info.dependencies);
  }
})(tree.dependencies);

// ---- Rust crates linked into the Windows exe (normal dependencies only) ----
const meta = JSON.parse(
  execFileSync('cargo', ['metadata', '--format-version', '1', '--filter-platform', 'x86_64-pc-windows-msvc'], {
    cwd: join(root, 'src-tauri'),
    encoding: 'utf8',
    maxBuffer: 256 * 1024 * 1024,
  }),
);
const packages = new Map(meta.packages.map((p) => [p.id, p]));
const nodes = new Map(meta.resolve.nodes.map((n) => [n.id, n]));
const crates = new Map();
const stack = [meta.resolve.root];
const seen = new Set();
while (stack.length) {
  const id = stack.pop();
  if (seen.has(id)) continue;
  seen.add(id);
  for (const d of nodes.get(id).deps) if (d.dep_kinds.some((k) => k.kind === null || k.kind === 'normal')) stack.push(d.pkg);
}
seen.delete(meta.resolve.root);
for (const id of seen) {
  const p = packages.get(id);
  const dir = dirname(p.manifest_path);
  crates.set(`${p.name}@${p.version}`, {
    name: p.name,
    version: p.version,
    license: p.license ?? (p.license_file ? 'see texts' : 'unspecified'),
    texts: licenseTexts(dir, p.license_file ? [p.license_file] : []),
    source: `https://crates.io/crates/${p.name}/${p.version}`,
  });
}

// ---- assets ----
const assets = [
  {
    name: 'Inter',
    version: '4 (variable)',
    license: 'OFL-1.1',
    texts: [['OFL.txt', readFileSync(join(root, 'src/assets/fonts/OFL.txt'), 'utf8').trim()]],
    source: 'https://rsms.me/inter/',
  },
];

// ---- write, sharing identical texts ----
const textIds = new Map();
const textList = [];
const ref = (text) => {
  if (!textIds.has(text)) {
    textIds.set(text, textList.length + 1);
    textList.push(text);
  }
  return textIds.get(text);
};
const row = (e) => {
  const spdx = e.license.split(/\s+(?:OR|AND)\s+|\//).filter((id) => /^[\w.+-]+$/.test(id));
  const refs =
    e.texts.map(([f, t]) => `[T${ref(t)}](#t${ref(t)}) ${f}`).join(', ') ||
    `no license file in the package: ${spdx.map((id) => `https://spdx.org/licenses/${id}.html`).join(', ')}`;
  return `| ${e.name} | ${e.version} | ${e.license} | ${refs} | ${e.source} |`;
};
const table = (entries) =>
  ['| Component | Version | License | Texts | Source |', '| --- | --- | --- | --- | --- |', ...[...entries].sort((a, b) => a.name.localeCompare(b.name)).map(row)].join('\n');

const out = `# Third-party notices

Preview for Windows is Copyright © 2026 Sanghae and licensed under the GNU Affero General
Public License v3.0 only (see \`LICENSE\`). It is built from and ships the third-party
components below, which remain under their own licenses.
This file is generated by \`node scripts/third-party-notices.mjs\`.

## Splash photo

The splash image (\`src/assets/splash.jpg\`, rendered from \`scripts/splash/\`) uses a photo by
Vincent Yap on Unsplash (https://unsplash.com/photos/yGykQCIecbM), under the Unsplash License
(https://unsplash.com/license). The name on it is set in EB Garamond (SIL Open Font License
1.1, https://github.com/octaviopardo/EBGaramond12); only the rendered image ships.

## Fonts

${table(assets)}

## JavaScript packages in the app bundle

${table(npm.values())}

## Rust crates in Preview.exe

${table(crates.values())}

## License texts

${textList.map((t, i) => `<a id="t${i + 1}"></a>\n### T${i + 1}\n\n\`\`\`\`text\n${t}\n\`\`\`\``).join('\n\n')}
`;
writeFileSync(join(root, 'THIRD_PARTY_NOTICES.md'), out);
console.log(`THIRD_PARTY_NOTICES.md: ${npm.size} npm packages, ${crates.size} crates, ${textList.length} distinct license texts, ${Math.round(out.length / 1024)} KB`);
